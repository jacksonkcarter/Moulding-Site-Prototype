/** Blank / missing ZIP keyed by normalized name|address1|state. */
const ZIP_CORRECTIONS_BY_ADDRESS = {
  "bfs|3661 west blue heron blvd|fl": "33404", // Builders FirstSource, Riviera Beach, FL
};

function trimCell(value) {
  return String(value ?? "")
    .replace(/\u00a0/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function normalizeZip(value) {
  const digits = String(value ?? "").replace(/\D/g, "");
  if (!digits) return "";
  return digits.slice(0, 5).padStart(5, "0");
}

function addressKey(name, address1, state) {
  return [name, address1, state]
    .map((part) => trimCell(part).toLowerCase())
    .join("|");
}

function resolveZip(row) {
  const name = trimCell(row.STCustomer);
  const address1 = trimCell(row.STAddress1);
  const state = trimCell(row.STState).toUpperCase();
  let zip = normalizeZip(row.STZip);

  if (!zip) {
    const fromAddress = ZIP_CORRECTIONS_BY_ADDRESS[addressKey(name, address1, state)];
    if (fromAddress) return { zip: fromAddress, corrected: true };
    return { zip: "", corrected: false };
  }

  const fromBad = ZIP_CORRECTIONS_BY_BAD_ZIP[zip];
  if (fromBad) return { zip: fromBad, corrected: true };
  return { zip, corrected: false };
}

function main() {
  if (!fs.existsSync(EXCEL_PATH)) {
    console.error(`Missing dealer list: ${EXCEL_PATH}`);
    process.exit(1);
  }

  const wb = XLSX.readFile(EXCEL_PATH);
  const sheetName = wb.SheetNames[0];
  const sheet = wb.Sheets[sheetName];
  const rows = XLSX.utils.sheet_to_json(sheet, { defval: "" });

  const dealers = [];
  let skippedNoZip = 0;
  let skippedNoCoords = 0;
  let corrected = 0;

  for (let i = 0; i < rows.length; i++) {
    const row = rows[i];
    const name = trimCell(row.STCustomer);
    const address1 = trimCell(row.STAddress1);
    const address2 = trimCell(row.STAddress2);
    const city = trimCell(row.STCity);
    const state = trimCell(row.STState).toUpperCase();
    const phone = trimCell(row.STPhone);
    const resolved = resolveZip(row);
    const zip = resolved.zip;

    if (resolved.corrected) {
      corrected += 1;
    }

    if (!name || !zip) {
      skippedNoZip += 1;
      continue;
    }

    const lookup = zipcodes.lookup(zip);
    if (!lookup || lookup.latitude == null || lookup.longitude == null) {
      skippedNoCoords += 1;
      console.warn(`No coords for ${name} (${city}, ${state} ${zip})`);
      continue;
    }

    const address = [address1, address2].filter(Boolean).join(", ");

    dealers.push({
      id: `d${i + 1}`,
      name,
      lat: Number(lookup.latitude),
      lng: Number(lookup.longitude),
      address,
      city,
      state,
      zip,
      phone,
    });
  }

  if (corrected > 0) {
    console.log(`Applied ${corrected} ZIP correction(s) in memory`);
  }

  const lines = [
    "/** Auto-generated by scripts/generate-dealers.js - do not edit by hand. */",
    "export type Dealer = {",
    "  id: string;",
    "  name: string;",
    "  lat: number;",
    "  lng: number;",
    "  address: string;",
    "  city: string;",
    "  state: string;",
    "  zip: string;",
    "  phone: string;",
    "};",
    "",
    `export const DEALERS: Dealer[] = ${JSON.stringify(dealers, null, 2)};`,
    "",
  ];

  fs.writeFileSync(OUTPUT_PATH, lines.join("\n"), "utf8");
  console.log(
    `Wrote ${dealers.length} dealers to ${path.relative(PROJECT_ROOT, OUTPUT_PATH)}` +
      ` (corrected zips: ${corrected}, skipped no zip: ${skippedNoZip}, skipped no coords: ${skippedNoCoords})`,
  );
}

main();
