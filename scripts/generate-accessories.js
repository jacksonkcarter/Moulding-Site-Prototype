/**
 * Scan Project_Info/Accessories folders → src/data/accessories.ts
 * and copy images to public/accessories/{category-slug}/.
 *
 * Run: npm run generate-accessories
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const ACCESSORIES_ROOT = path.join(ROOT, "Project_Info", "Accessories");
const PUBLIC_ACCESSORIES = path.join(ROOT, "public", "accessories");
const OUTPUT_PATH = path.join(ROOT, "src", "data", "accessories.ts");

const IMAGE_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".gif", ".webp", ".tif", ".tiff"]);

function slugify(label) {
  return label
    .trim()
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function productNameFromFilename(filename) {
  return path.parse(filename).name;
}

function copyDirSync(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const name of fs.readdirSync(src)) {
    const s = path.join(src, name);
    const d = path.join(dest, name);
    if (fs.statSync(s).isDirectory()) copyDirSync(s, d);
    else fs.copyFileSync(s, d);
  }
}

function main() {
  if (!fs.existsSync(ACCESSORIES_ROOT)) {
    console.error("Missing", ACCESSORIES_ROOT);
    process.exit(1);
  }

  if (fs.existsSync(PUBLIC_ACCESSORIES)) {
    fs.rmSync(PUBLIC_ACCESSORIES, { recursive: true, force: true });
  }
  fs.mkdirSync(PUBLIC_ACCESSORIES, { recursive: true });

  const categories = [];
  const products = [];

  const dirs = fs
    .readdirSync(ACCESSORIES_ROOT, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .sort((a, b) => a.name.localeCompare(b.name, undefined, { sensitivity: "base" }));

  for (const dir of dirs) {
    const label = dir.name;
    const slug = slugify(label);
    const folderPath = path.join(ACCESSORIES_ROOT, label);
    const publicFolder = path.join(PUBLIC_ACCESSORIES, slug);
    fs.mkdirSync(publicFolder, { recursive: true });

    const files = fs
      .readdirSync(folderPath)
      .filter((name) => IMAGE_EXTENSIONS.has(path.extname(name).toLowerCase()))
      .sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base" }));

    let thumbnailSrc = null;
    const categoryProducts = [];

    for (const file of files) {
      const destName = file;
      fs.copyFileSync(path.join(folderPath, file), path.join(publicFolder, destName));
      const publicSrc = `/accessories/${slug}/${destName}`;
      const name = productNameFromFilename(file);
      const product = {
        id: `${slug}/${name}`,
        name,
        categorySlug: slug,
        categoryLabel: label,
        imageSrc: publicSrc,
      };
      categoryProducts.push(product);
      products.push(product);
      if (!thumbnailSrc) thumbnailSrc = publicSrc;
    }

    categories.push({
      label,
      slug,
      thumbnailSrc,
      productCount: categoryProducts.length,
    });
  }

  const out = `// Generated by scripts/generate-accessories.js - do not edit by hand.
// Run: npm run generate-accessories

export type AccessoryCategory = {
  label: string;
  slug: string;
  thumbnailSrc: string | null;
  productCount: number;
};

export type AccessoryProduct = {
  id: string;
  name: string;
  categorySlug: string;
  categoryLabel: string;
  imageSrc: string;
};

export const ACCESSORY_CATEGORIES: AccessoryCategory[] = ${JSON.stringify(categories, null, 2)};

export const ACCESSORY_PRODUCTS: AccessoryProduct[] = ${JSON.stringify(products, null, 2)};

export function getAccessoryCategory(slug: string): AccessoryCategory | undefined {
  return ACCESSORY_CATEGORIES.find((c) => c.slug === slug);
}

export function getAccessoryProductsByCategory(slug: string): AccessoryProduct[] {
  return ACCESSORY_PRODUCTS.filter((p) => p.categorySlug === slug);
}
`;

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, out, "utf8");
  console.log("Wrote", OUTPUT_PATH);
  console.log(`Categories: ${categories.length}, products: ${products.length}`);
  console.log("Copied images to public/accessories");
}

main();
