/**
 * Sync home-page hero slideshow images from Project_Info/Home-Page-Images → public/home-page
 * and regenerate src/data/home-page-images.ts.
 *
 * Run: node scripts/sync-home-page-images.js
 * (or: npm run sync-home-page-images)
 *
 * Only files currently in the source folder are used. Old public copies are removed.
 * Public filenames include a content hash so browsers/Next never serve a stale image.
 */
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const PROJECT_ROOT = path.join(__dirname, "..");
const SOURCE_DIR = path.join(PROJECT_ROOT, "Project_Info", "Home-Page-Images");
const PUBLIC_DIR = path.join(PROJECT_ROOT, "public", "home-page");
const OUTPUT_PATH = path.join(PROJECT_ROOT, "src", "data", "home-page-images.ts");
const IMAGE_EXT = /\.(jpe?g|png|webp|gif)$/i;

function slugify(name) {
  return name
    .replace(IMAGE_EXT, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

function main() {
  if (!fs.existsSync(SOURCE_DIR)) {
    console.error("Source folder not found:", SOURCE_DIR);
    process.exit(1);
  }

  const sourceFiles = fs
    .readdirSync(SOURCE_DIR)
    .filter((name) => IMAGE_EXT.test(name))
    .sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base" }));

  fs.mkdirSync(PUBLIC_DIR, { recursive: true });
  for (const existing of fs.readdirSync(PUBLIC_DIR)) {
    fs.unlinkSync(path.join(PUBLIC_DIR, existing));
  }

  const publicPaths = [];
  for (const name of sourceFiles) {
    const srcPath = path.join(SOURCE_DIR, name);
    const buf = fs.readFileSync(srcPath);
    const hash = crypto.createHash("md5").update(buf).digest("hex").slice(0, 8);
    const ext = path.extname(name).toLowerCase();
    const publicName = `${slugify(name)}-${hash}${ext}`;
    fs.writeFileSync(path.join(PUBLIC_DIR, publicName), buf);
    publicPaths.push(`/home-page/${publicName}`);
    console.log("Synced", name, "→", publicName);
  }

  const out = `// Generated by scripts/sync-home-page-images.js — do not edit by hand.
// Run: npm run sync-home-page-images
// Source: Project_Info/Home-Page-Images

export const HOME_PAGE_HERO_IMAGES: string[] = ${JSON.stringify(publicPaths, null, 2)};
`;

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, out, "utf8");
  console.log("Wrote", OUTPUT_PATH);
  console.log(`Hero slideshow will use ${publicPaths.length} image(s).`);
}

main();
