/**
 * Sync moulding-type thumbnails from
 * Project_Info/Moulding-Type-Thumbnail-Images → public/moulding-type-thumbnails
 * and regenerate src/data/moulding-type-thumbnails.ts.
 *
 * Run: npm run sync-moulding-type-thumbnails
 */
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const PROJECT_ROOT = path.join(__dirname, "..");
const SOURCE_DIR = path.join(PROJECT_ROOT, "Project_Info", "Moulding-Type-Thumbnail-Images");
const PUBLIC_DIR = path.join(PROJECT_ROOT, "public", "moulding-type-thumbnails");
const TYPES_PATH = path.join(PROJECT_ROOT, "src", "data", "profile-moulding-types.ts");
const OUTPUT_PATH = path.join(PROJECT_ROOT, "src", "data", "moulding-type-thumbnails.ts");
const IMAGE_EXT = /\.(jpe?g|png|webp|gif)$/i;

function slugify(name) {
  return name
    .replace(IMAGE_EXT, "")
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

function normalizeTypeKey(name) {
  return String(name)
    .replace(IMAGE_EXT, "")
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ");
}

function loadProfileTypes() {
  const source = fs.readFileSync(TYPES_PATH, "utf8");
  const match = source.match(/export const PROFILE_MOULDING_TYPES = (\[[\s\S]*?\]) as const;/);
  if (!match) {
    throw new Error("Could not parse PROFILE_MOULDING_TYPES from " + TYPES_PATH);
  }
  return JSON.parse(match[1]);
}

function main() {
  if (!fs.existsSync(SOURCE_DIR)) {
    console.error("Source folder not found:", SOURCE_DIR);
    process.exit(1);
  }

  const types = loadProfileTypes();
  const sourceFiles = fs.readdirSync(SOURCE_DIR).filter((name) => IMAGE_EXT.test(name));

  fs.mkdirSync(PUBLIC_DIR, { recursive: true });
  for (const existing of fs.readdirSync(PUBLIC_DIR)) {
    fs.unlinkSync(path.join(PUBLIC_DIR, existing));
  }

  /** @type {Map<string, string>} */
  const byTypeKey = new Map();

  for (const name of sourceFiles) {
    const srcPath = path.join(SOURCE_DIR, name);
    const buf = fs.readFileSync(srcPath);
    const hash = crypto.createHash("md5").update(buf).digest("hex").slice(0, 8);
    const ext = path.extname(name).toLowerCase();
    const publicName = `${slugify(name)}-${hash}${ext}`;
    fs.writeFileSync(path.join(PUBLIC_DIR, publicName), buf);
    byTypeKey.set(normalizeTypeKey(name), `/moulding-type-thumbnails/${publicName}`);
    console.log("Synced", name, "→", publicName);
  }

  /** @type {Record<string, string>} */
  const thumbnails = {};
  let matched = 0;
  for (const type of types) {
    const src = byTypeKey.get(normalizeTypeKey(type));
    if (src) {
      thumbnails[type] = src;
      matched += 1;
    } else {
      console.warn("No thumbnail for moulding type:", type);
    }
  }

  for (const [key, src] of byTypeKey) {
    const typeMatch = types.find((t) => normalizeTypeKey(t) === key);
    if (!typeMatch) {
      console.warn("Thumbnail has no matching PROFILE_MOULDING_TYPES entry:", key, src);
    }
  }

  const out = `// Generated by scripts/sync-moulding-type-thumbnails.js — do not edit by hand.
// Run: npm run sync-moulding-type-thumbnails
// Source: Project_Info/Moulding-Type-Thumbnail-Images

/** Thumbnail path for each select-profile moulding type that has an image. */
export const MOULDING_TYPE_THUMBNAILS: Record<string, string> = ${JSON.stringify(thumbnails, null, 2)};
`;

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, out, "utf8");
  console.log("Wrote", OUTPUT_PATH);
  console.log(`Matched ${matched}/${types.length} moulding types.`);
}

main();
